export const tagTable: MockTableStore<TagItem> = createMockTable(TAG_SEED, "TAG");

/** 标签维度表的统计口径(维度数 / 有备注的维度 / 已挂标签的维度) */
export function tagDimensionStats(rows: readonly TagDimension[]) {
	return {
		标签维度: rows.length,
		有备注维度: rows.filter((row) => row.备注.trim().length > 0).length,
		已挂标签维度: new Set(TAG_SEED.map((tag) => tag.维度)).size,
	};
}

/** 标签明细表的统计口径(标签数 / 含义完整数 / 覆盖维度数) */
export function tagStats(rows: readonly TagItem[]) {
	return {
		标签总数: rows.length,
		含义完整: rows.filter((row) => row.含义.trim().length > 0).length,
		覆盖维度数: new Set(rows.map((row) => row.维度)).size,
	};
}

/** 某个维度下的标签数(维度表「标签数」派生列与筛选 chip 计数共用) */
export function tagCountOfDimension(dimension: string): number {
	return tagTable.getState().rows.filter((row) => String(row.维度) === dimension).length;
}

